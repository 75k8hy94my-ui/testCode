import { test, expect } from '@playwright/test';

test('guest configures a property, saves it on a video, filters, and reads it on playback', async ({ page }) => {
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.addInitScript(() => sessionStorage.setItem('testCode.guestMode.v1', '1'));
  await page.goto('video.html');
  await expect(page.locator('#videoLibraryApp')).toBeVisible();
  await page.getByRole('link', { name: 'プロパティ設定' }).click();
  await expect(page.locator('#videoPropertySettings')).toBeVisible();
  await page.getByLabel('新しい項目名').fill('時間帯');
  await page.getByLabel('新しい項目の種類').selectOption('single_select');
  await page.getByRole('button', { name: '項目を追加' }).click();
  await expect(page.getByLabel('項目名', { exact: true })).toHaveValue('時間帯');
  await page.getByLabel('動画カードに表示').check();
  await page.getByLabel('時間帯の選択肢名').fill('朝');
  await page.getByRole('button', { name: '選択肢を追加' }).click();
  await expect(page.getByLabel('朝の選択肢名')).toBeVisible();
  await page.getByLabel('時間帯の選択肢名').fill('夜');
  await page.getByRole('button', { name: '選択肢を追加' }).click();
  await page.getByRole('link', { name: '動画一覧へ' }).click();
  await expect(page.locator('#videoLibraryApp')).toBeVisible();
  await page.getByRole('button', { name: /追加/ }).click();
  await expect(page).toHaveURL(/video-edit\.html\?mode=add/);
  await page.locator('#videoEditTitle').fill('プロパティ検証動画');
  await page.locator('#videoEditUrl').fill('https://example.com/property-check.mp4');
  await page.getByRole('button', { name: '朝', exact: true }).click();
  await page.getByRole('button', { name: '追加', exact: true }).click();
  await expect(page).toHaveURL(/video\.html$/);
  await expect(page.getByText('時間帯: 朝')).toBeVisible();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await expect(page.getByText('時間帯: 朝')).toBeVisible();
  await page.getByText('カスタムプロパティで絞り込む').click();
  await page.getByLabel('時間帯の条件').selectOption('equals');
  await page.getByLabel('時間帯の値').selectOption({ label: '朝' });
  await expect(page.locator('#videoLibraryCount')).toContainText('1 / 1');
  await page.locator('.vl-edit-link').click();
  await expect(page).toHaveURL(/video-edit\.html\?id=/);
  await expect(page.getByRole('button', { name: '朝', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: '夜', exact: true }).click();
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(page).toHaveURL(/video\.html$/);
  await expect(page.getByText('時間帯: 夜')).toBeVisible();
  await page.getByText('カスタムプロパティで絞り込む').click();
  await page.getByLabel('時間帯の値').selectOption({ label: '夜' });
  await expect(page.locator('#videoLibraryCount')).toContainText('1 / 1');
  await page.locator('.vl-open').click();
  await expect(page).toHaveURL(/video-player\.html\?id=/);
  await page.getByText('プロパティ', { exact: true }).click();
  await expect(page.getByText('時間帯：')).toBeVisible();
  await expect(page.getByText('夜', { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
