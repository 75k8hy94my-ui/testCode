function lawRecords({ subject, lawName, lawId, prefix, entries }) {
  return entries.map(([article, story, examPoint, tags]) => ({
    id: `${prefix}-${article}`,
    subject,
    lawName,
    lawId,
    article,
    paragraph: '',
    elm: `MainProvision-Article_${article}`,
    text: '',
    story,
    examPoint,
    tags,
    sourceUrl: `https://laws.e-gov.go.jp/law/${lawId}`,
    verifiedOn: VERIFIED_ON
  }));
}

