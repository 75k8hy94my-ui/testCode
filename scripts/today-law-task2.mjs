async function fetchOfficialText(record) {
  const url = buildEgovVerificationUrl(record);
  let lastError = null;
  for (let attempt = 1; attempt <= 5; attempt += 1) {
    try {
      const response = await fetch(url, { headers:{ accept:'application/json' } });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const json = await response.json();
      if (!json || json.law_full_text == null) throw new Error('missing law_full_text');
      const text = normalizeStatutoryText(extractTextLeaves(json.law_full_text));
      if (!text) throw new Error('empty statutory text');
      return text;
    } catch (error) {
      lastError = error;
      if (attempt < 5) await sleep(250 * attempt);
    }
  }
  throw new Error(`${record.id}: failed to fetch ${url}: ${lastError?.message || lastError}`);
}

